import { resolve } from 'node:path';
import sharp from 'sharp';
import { db as sharedDb } from '../server/db';
import knex from 'knex';
import { hashPassword } from '../server/auth';
const id = randomUUID(), mediaId = randomUUID(), userId = randomUUID();
const db = knex(sharedDb.client.config);
const slug = `browser-product-${id}`, email = `product-${id}@test.invalid`, password = randomUUID();
const uploads = resolve(process.env.UPLOAD_DIR || 'data/uploads');
const cover = `/uploads/${mediaId}.webp`;
const fixture = { title: 'Produk pengujian', slug, summary: 'Contoh khusus pengujian portofolio, tidak diterbitkan ke situs produksi.', category: 'Pengujian', cover, coverAlt: 'Ilustrasi sekolah untuk pengujian', blocks: [{ type:'paragraph', text:'Keterangan produk untuk pengujian tampilan.' }], screenshots: [{ image:cover, alt:'Tangkapan layar contoh pengujian', caption:'Keterangan tampilan' }], videoUrl:'https://example.com/demo.mp4', videoTranscript:'Video memperlihatkan alur pembelajaran sekolah.', websiteUrl:'https://example.com', seoTitle:'', seoDescription:'' };
test.beforeAll(async () => {
  await mkdir(uploads, {recursive:true});
  await sharp('public/school-poster.png').webp().toFile(resolve(uploads, mediaId+'.webp'));
  await db('media').insert({id:mediaId,url:cover,name:'Product test screenshot',size:1000,created_at:new Date().toISOString()});
  await db('documents').insert({id,kind:'product',revision:1,status:'published',draft:JSON.stringify(fixture),published:JSON.stringify(fixture),slug,published_slug:slug,updated_at:new Date().toISOString(),published_at:new Date().toISOString()});
  await db('users').insert({id:userId,email,name:'Product Test',role:'admin',password:await hashPassword(password),active:true});
});
test.afterAll(async () => { await db('documents').where({id}).orWhere({slug:slug+'-draft'}).delete(); await db('users').where({id:userId}).delete(); await db('media').where({id:mediaId}).delete(); await rm(resolve(uploads,mediaId+'.webp'),{force:true}); await db.destroy(); });
